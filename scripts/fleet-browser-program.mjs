// Make (or, with --check, verify) the browser lane's rewrite program from the pinned protocol and the frozen spec:
//   node scripts/fleet-browser-program.mjs [--check] [--flat FILE]
// It refuses unless both inputs have their pinned hashes and the resolver finds no problem. --flat writes the
// expanded listing (every concrete path), the form the reviewers read.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { resolve } from "../lib/fleet/browser/resolve.mjs";
import { PINS } from "../lib/fleet/browser/pins.mjs";

const root = new URL("..", import.meta.url);
const hex = (b) => createHash("sha256").update(b).digest("hex");
const read = (f, sha) => { const b = readFileSync(new URL(f, root)); if (hex(b) !== sha) { console.error(`${f}: sha256 ${hex(b)}, pinned ${sha}`); process.exit(1); } return JSON.parse(b); };
const proto = read(PINS.protocol.file, PINS.protocol.sha256), spec = read(PINS.spec.file, PINS.spec.sha256);
const { program, flat, problems } = resolve(proto, spec);
if (problems.length) { console.error(`${problems.length} problems:\n  ` + problems.join("\n  ")); process.exit(1); }
const out = JSON.stringify({ $comment: "GENERATED by scripts/fleet-browser-program.mjs from the pinned protocol and the frozen spec (lib/fleet/browser/pins.mjs). Don't edit.", protocol: { file: PINS.protocol.file, sha256: PINS.protocol.sha256 }, spec: { file: PINS.spec.file, sha256: PINS.spec.sha256 }, owners: program.owners, types: program.types }, null, 1) + "\n";
const flatAt = process.argv.indexOf("--flat");
if (flatAt > 0) writeFileSync(process.argv[flatAt + 1], JSON.stringify(flat, null, 1) + "\n");
const c = (a) => flat.filter((r) => r.action.startsWith(a)).length;
console.log(`${flat.length} locations: ${c("map")} mapped, ${c("drop")} dropped, ${c("keep")} kept, ${c("recurse")} recursive; ${Object.keys(program.owners).length} owners, ${Object.keys(program.types).length} types; program sha256 ${hex(out)}`);
if (process.argv.includes("--check")) {
  const have = readFileSync(new URL(PINS.program.file, root), "utf8");
  if (have !== out || hex(have) !== PINS.program.sha256) { console.error("the checked-in program isn't what the resolver makes, or isn't the pinned one"); process.exit(1); }
  console.log("the checked-in program matches");
} else writeFileSync(new URL(PINS.program.file, root), out);
