#!/usr/bin/env node
// The third-party list of the backup binary (backup/THIRD-PARTY.txt): every crate linked into it on Linux, with its
// version, license and source, from `cargo metadata` on the committed lock file. Build-only crates (build scripts and
// proc macros) aren't linked, so they aren't listed.
//   node scripts/backup-third-party.mjs           write backup/THIRD-PARTY.txt
//   node scripts/backup-third-party.mjs --check   fail if it isn't up to date (CI)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = join(root, "backup", "Cargo.toml");
const out = join(root, "backup", "THIRD-PARTY.txt");

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--locked", "--format-version", "1", "--filter-platform", "x86_64-unknown-linux-gnu", "--manifest-path", manifest], {
    encoding: "utf8",
    maxBuffer: 64 << 20,
  }),
);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const isProcMacro = (p) => p.targets.some((t) => t.kind.includes("proc-macro"));

// crates reachable from the binary through normal (linked) dependencies only
const seen = new Set();
const stack = [meta.resolve.root];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id).deps) {
    if (d.dep_kinds.some((k) => k.kind === null) && !isProcMacro(pkgs.get(d.pkg))) stack.push(d.pkg);
  }
}
seen.delete(meta.resolve.root);

const source = (p) => (p.source ?? "").replace(/^registry\+https:\/\/github\.com\/rust-lang\/crates\.io-index$/, "crates.io").replace(/^git\+/, "");
const rows = [...seen].map((id) => pkgs.get(id)).map((p) => `${p.name} ${p.version}\t${p.license ?? "(none)"}\t${source(p)}`);
rows.sort();
const text =
  "# Crates linked into sagebrush-agent-backup on Linux: name version, license, source.\n" +
  "# Generated by scripts/backup-third-party.mjs from backup/Cargo.lock; do not edit by hand.\n" +
  rows.join("\n") +
  "\n";

if (process.argv.includes("--check")) {
  let have = "";
  try {
    have = readFileSync(out, "utf8");
  } catch {}
  if (have !== text) {
    console.error("backup/THIRD-PARTY.txt is out of date: run node scripts/backup-third-party.mjs");
    process.exit(1);
  }
  console.log(`backup/THIRD-PARTY.txt is up to date (${rows.length} crates)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote backup/THIRD-PARTY.txt (${rows.length} crates)`);
}
